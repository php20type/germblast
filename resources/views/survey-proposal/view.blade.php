        <h1 style="margin-top: 30px;">GermBlast Service - Description</h1>

        <div class="services-section">
            <div class="service-item">
                <h3>GermBlast Pretreatment</h3>
                <p>
                    Before a surface can be disinfected, it must first be cleaned. GermBlast staff utilize disposable,
                    antimicrobial microfiber cloths in conjunction with a pretreatment chemical, Oxivir Five 16 or
                    Opti-cide 3. GermBlast Pretreatment breaks through biofilm allowing for a more efficient sanitizing
                    and disinfecting step.
                </p>
            </div>

            <div class="service-item">
                <h3>GermBlast Spray</h3>
                <p>
                    GermBlast Spray utilizes a rapid kill surface disinfectant. This powerful, hospital-grade
                    disinfectant kills 99.999% of detectable pathogens. State of the art spraying systems help
                    technicians achieve an efficient coverage. This GermBlast Spray modality is non-corrosive,
                    non-toxic, and non-staining.
                </p>
            </div>

            <div class="service-item">
                <h3>GermBlast Steam</h3>
                <p>
                    GermBlast Steam offers a unique solution that allows an extremely high level of cleanliness while
                    disinfecting the establishment, the dual purpose cleaning makes the process much more effective. A
                    diverse assortment of pathogenic microorganisms can be rapidly killed by GermBlast Steam within 5
                    seconds. Risks of infection from contaminated surfaces will decrease further with more frequent
                    treatments.
                </p>
            </div>

            <div class="service-item">
                <h3>GermBlast PCO (Photocatalytic Oxidation)</h3>
                <p>
                    GermBlast UV-PCO is one of the most effective air purification devices. It is capable of
                    disinfecting over 60 harmful airborne pathogens including norovirus, tuberculosis, pneumonia, and
                    influenza virus. UV-PCO creates a reaction between ultraviolet light and a titanium dioxide based
                    catalyst in the presence of water that oxidizes and eliminates microorganisms circulating in the
                    air.
                </p>
            </div>

            <div class="service-item">
                <h3>GermBlast H2O2</h3>
                <p>
                    GermBlast Dry Mist H2O2 utilizes a hydrogen peroxide and silver based disinfectant to eliminate the
                    most robust microorganisms in an environment. This modality utilizes dry mist technology to atomize
                    the disinfectant and distribute it throughout the environment ensuring complete coverage of an area
                    from ceiling to floor. GermBlast H2O2 will not damage electronics or surfaces and breaks down into
                    oxygen and water without leaving a residue.
                </p>
            </div>

            <div class="service-item">
                <h3>GermBlast Shield</h3>
                <p>
                    GermBlast Shield employs an innovative polymer that adheres to surfaces and inhibits odor-causing
                    microorganism colonization, yet is safe to touch. The polymer is applied using electrostatic
                    spraying technology that ensure 100% coverage by negatively charging chemicals, causing them to
                    completely and efficiently cover every surface. Surface protection lasts for up to 90 days.
                </p>
            </div>
